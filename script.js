function projectObject(p, point, normal, size, anchor, alpha, glow = 0, relief = 1) {
  if (motionFrame.tiltX || motionFrame.tiltY) {
    point=rotate3D(point,motionFrame.tiltX*.055,motionFrame.tiltY*.045);
    normal=rotate3D(normal,motionFrame.tiltX*.055,motionFrame.tiltY*.045);
  }
  const perspective = 1/(1-point.z*.20);
  const face = clamp((normal.z+.22)/1.22, 0, 1);
  const light = clamp(normal.x*-.34+normal.y*-.52+normal.z*.78, 0, 1);
  const facing=normal.z<0?.025:.28+.72*Math.sqrt(normal.z);
  const depthLight = (.18+face*.86+light*.48)*facing;
  return {x:anchor.x*width+point.x*size*perspective,
    y:anchor.y*height+point.y*size*perspective,
    z:point.z, scale:perspective, normal,
    alpha:alpha*depthLight*relief, glow, surface:1,
    color:p.color};
}
let bubblePoseCache = null;
function bubblePoses(time,mobile) {
  if (bubblePoseCache?.time===time && bubblePoseCache.width===width && bubblePoseCache.height===height) return bubblePoseCache;
  const base=mobile?Math.min(width*.235,98):Math.min(width*.115,164);
  const approach=clamp(.5+.25*Math.sin(time*.0041+.4)+.16*Math.sin(time*.0073+1.8)+.09*Math.sin(time*.0017-.5),0,1);
  const span=base*(2.10-.27*approach);
  const centerX=(mobile?.50:.25)*width+base*.035*Math.sin(time*.0019);
  const centerY=(mobile?.28:.50)*height;
  const poses=[
    {size:base*1.06,x:centerX-span*.47+base*.018*Math.sin(time*.0021),
      y:centerY-base*.12+base*.13*Math.sin(time*.0021+.4)+base*.04*Math.cos(time*.0041),
      yaw:.32+Math.sin(time*.0023)*.28,pitch:Math.sin(time*.0031+.6)*.14,
      roll:-.17+Math.sin(time*.0018)*.11},
    {size:base*.90,x:centerX+span*.53+base*.024*Math.sin(time*.0013+2),
      y:centerY+base*.09+base*.11*Math.sin(time*.0016+2.3)+base*.035*Math.sin(time*.0037+1),
      yaw:-.35+Math.sin(time*.0017+1.2)*.34,pitch:Math.sin(time*.0022+1.9)*.17,
      roll:.22+Math.sin(time*.0027+2)*.12}
  ];
  const dx=poses[1].x-poses[0].x,dy=poses[1].y-poses[0].y;
  const weight=poses[0].size/(poses[0].size+poses[1].size);
  bubblePoseCache={time,width,height,base,poses,
    contact:{x:poses[0].x+dx*weight,y:poses[0].y+dy*weight,
      strength:Math.exp(-(((Math.hypot(dx,dy)/base-1.87)/.12)**2))}};
  return bubblePoseCache;
}
function dialogueCycle(time) {
  if(reduceMotion.matches) return {round:0,progress:0,fusion:0,state:"separate"};
  const cycle=time/(60*30);
  const progress=cycle-Math.floor(cycle);
  const smooth=(a,b)=>{const t=clamp((progress-a)/(b-a),0,1);return t*t*t*(t*(t*6-15)+10);};
  const fusion=progress<.34?smooth(.16,.34):progress<.48?1:1-smooth(.48,.70);
  const state=progress<.16||progress>=.70?"separate":progress<.34?"merging":progress<.48?"idea":"reforming";
  return {round:Math.floor(cycle)%2,progress,fusion,state};
}
let bulbPoseCache=null;
