const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));
const clamp = (n, low, high) => Math.max(low, Math.min(high, n));
const normalize = (v) => {
  const length = Math.hypot(v.x, v.y, v.z) || 1;
  return { x: v.x / length, y: v.y / length, z: v.z / length };
};
const cross = (a, b) => ({ x: a.y*b.z-a.z*b.y, y: a.z*b.x-a.x*b.z, z: a.x*b.y-a.y*b.x });
function spherePoint(index, count, shift = 0) {
  const y = 1 - 2 * (index + .5) / count;
  const ring = Math.sqrt(1 - y*y);
  const theta = index * GOLDEN_ANGLE + shift;
  return { x: Math.cos(theta)*ring, y, z: Math.sin(theta)*ring };
}
function rotate3D(v, yaw, pitch, roll = 0) {
  const x = v.x*Math.cos(yaw) + v.z*Math.sin(yaw);
  const z = v.z*Math.cos(yaw) - v.x*Math.sin(yaw);
  const y = v.y*Math.cos(pitch) - z*Math.sin(pitch);
  const depth = z*Math.cos(pitch) + v.y*Math.sin(pitch);
  return { x: x*Math.cos(roll)-y*Math.sin(roll), y: x*Math.sin(roll)+y*Math.cos(roll), z: depth };
}
