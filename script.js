const sulcusSegments = [];
for (const path of sulcusPaths) {
  let previous = path[0];
  for (let i=0;i<path.length-1;i++) {
    const a=path[Math.max(0,i-1)],b=path[i],c=path[i+1],d=path[Math.min(path.length-1,i+2)];
    for(let step=1;step<=10;step++) {
      const t=step/10,t2=t*t,t3=t2*t;
      const point=[0,1].map(k=>.5*((2*b[k])+(-a[k]+c[k])*t+(2*a[k]-5*b[k]+4*c[k]-d[k])*t2+(-a[k]+3*b[k]-3*c[k]+d[k])*t3));
      sulcusSegments.push([previous[0],previous[1],point[0]-previous[0],point[1]-previous[1]]);
      previous=point;
    }
  }
}
function distanceToSulcus(z,y) {
  let closest=Infinity;
  for (const [x0,y0,dx,dy] of sulcusSegments) {
    const t=clamp(((z-x0)*dx+(y-y0)*dy)/(dx*dx+dy*dy),0,1);
    const distance=(z-x0-t*dx)**2+(y-y0-t*dy)**2;
    closest=Math.min(closest,distance);
  }
  return Math.sqrt(closest);
}
function cortexSurface(n) {
  const side=n.x<0?-1:1;
  const lateral=Math.abs(n.x);
  const temporal=Math.exp(-(((n.z-.12)/.52)**2)-(((n.y-.55)/.34)**2))*lateral;
  // Flattened underside, elongated frontal/occipital axis, and a distinct temporal lobe.
  let y=-.13+n.y*(n.y<0?.78:.55)+temporal*.17;
  let z=n.z*(n.z>0?1.22:1.08);
  let x=.028+lateral*.81+temporal*.09;
  if(n.z<-.35 && n.y>0) y-=.12*n.y*Math.min(1,(-n.z-.35)/.4);
  // A deep longitudinal cleft separates the hemispheres, including at the crown.
  const fissure=Math.exp(-((n.x/.12)**2))*.18;
  y-=n.y*fissure;
  z-=n.z*fissure;
  x+=.007*Math.sin(n.z*8+n.y*5);
  const distance=distanceToSulcus(z+side*.025,y);
  const groove=.205*Math.exp(-((distance/.048)**2))*Math.min(1,lateral*3);
  const crown=.045*Math.exp(-((Math.sin(n.z*12+1.3*Math.sin(n.x*7))/.34)**2))*Math.max(0,-n.y);
  x-=groove*lateral;
  y-=n.y*(groove*.50+crown);
  z-=n.z*groove*.34;
  const contourAngle=Math.atan2(y+.13,z);
  const contour=.025*Math.sin(contourAngle*8+.7)+.018*Math.sin(contourAngle*13);
  y+=n.y*contour;z+=n.z*contour;
  return {x:side*x,y,z,groove:groove+crown};
}
function brainGeometry(index, count) {
  const cortexCount = Math.floor(count*.88);
  const cerebellumCount = Math.floor(count*.08);
  if (index < cortexCount) {
    const n = spherePoint(index, cortexCount);
    const point = cortexSurface(n);
    // Surface normals follow the actual relief, so folds remain visible as it turns.
    const tangent = normalize(cross(n, Math.abs(n.y) < .9 ? {x:0,y:1,z:0} : {x:1,y:0,z:0}));
    const bitangent = cross(n, tangent);
    const sample = (axis) => cortexSurface(normalize({x:n.x+axis.x*.002,y:n.y+axis.y*.002,z:n.z+axis.z*.002}));
    const u = sample(tangent), v = sample(bitangent);
    let normal = normalize(cross({x:u.x-point.x,y:u.y-point.y,z:u.z-point.z}, {x:v.x-point.x,y:v.y-point.y,z:v.z-point.z}));
    if (normal.x*n.x+normal.y*n.y+normal.z*n.z < 0) normal = {x:-normal.x,y:-normal.y,z:-normal.z};
    return {...point, normal, relief: Math.max(.18,1-point.groove*4.2)};
  }
  if (index < cortexCount+cerebellumCount) {
    const n = spherePoint(index-cortexCount, cerebellumCount);
    const ridge = 1 + .055*Math.sin(n.y*32);
    return {x:n.x*.43*ridge, y:.52+n.y*.25*ridge, z:-.70+n.z*.39,
      normal:n, relief:.82};
  }
  const t = (index-cortexCount-cerebellumCount)/(count-cortexCount-cerebellumCount);
  const angle = index*GOLDEN_ANGLE;
  const radius = .12*(1-t*.36);
  return {x:Math.cos(angle)*radius, y:.48+t*.28, z:-.40+Math.sin(angle)*radius-t*.28,
    normal:{x:Math.cos(angle),y:.18,z:Math.sin(angle)}, relief:.75};
}
function bubbleGeometry(index, count, pair) {
  const bodyCount = Math.floor(count*.86);
  if (index < bodyCount) {
    const n = spherePoint(index, bodyCount, pair*.7);
    // A rounded, inflated volume: visible front, rim and back, rather than a flat ring.
    const power = (value) => Math.sign(value)*Math.abs(value)**.88;
    return {x:power(n.x)*.94, y:power(n.y)*.70, z:power(n.z)*.62,
      normal:normalize({x:n.x/.94,y:n.y/.70,z:n.z/.62}), relief:1};
  }
  // A tapered, three-dimensional speech tail. It joins the lower outer flank.
  const t = (index-bodyCount+.5)/(count-bodyCount);
  const angle = index*GOLDEN_ANGLE;
  const side = pair ? 1 : -1;
  const radius = .23*(1-t);
  return {x:side*(.42+.33*t)+Math.cos(angle)*radius,
    y:.48+.55*t, z:.04+Math.sin(angle)*radius*.68,
    normal:normalize({x:Math.cos(angle),y:.35,z:Math.sin(angle)}), relief:1};
}
