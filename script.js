function bulbRadius(y) {
  let i=0;
  while(i<bulbProfile.length-2 && y>bulbProfile[i+1][0]) i++;
  const [a,r0]=bulbProfile[i], [b,r1]=bulbProfile[i+1];
  const t=clamp((y-a)/(b-a),0,1);
  const left=bulbProfile[Math.max(0,i-1)],right=bulbProfile[Math.min(bulbProfile.length-1,i+2)];
  const m0=(r1-left[1])/(b-left[0])*(b-a),m1=(right[1]-r0)/(right[0]-a)*(b-a);
  let radius=(2*t*t*t-3*t*t+1)*r0+(t*t*t-2*t*t+t)*m0+(-2*t*t*t+3*t*t)*r1+(t*t*t-t*t)*m1;
  if(y>.50 && y<.84) radius+=.022*Math.sin((y-.50)*Math.PI*25);
  return Math.max(.001,radius);
}
const bulbRings=[];
let bulbArea=0;
for(let i=0;i<220;i++) {
  const y=-1.15+(i+.5)/220*2.11,dy=2.11/220;
  const radius=bulbRadius(y),slope=(bulbRadius(y+.003)-bulbRadius(y-.003))/.006;
  bulbArea+=radius*Math.sqrt(1+slope*slope)*dy;
  bulbRings.push({y,radius,slope,area:bulbArea});
}
function bulbGeometry(index,count) {
  const area=(index+.5)/count*bulbArea;
  let low=0,high=bulbRings.length-1;
  while(low<high){const middle=(low+high)>>1;if(bulbRings[middle].area<area)low=middle+1;else high=middle;}
  const ring=bulbRings[low],previousArea=low?bulbRings[low-1].area:0;
  const fraction=(area-previousArea)/(ring.area-previousArea);
  const y=ring.y+(fraction-.5)*(2.11/220),radius=bulbRadius(y);
  const angle=index*GOLDEN_ANGLE;
  return {x:Math.cos(angle)*radius,y,z:Math.sin(angle)*radius,
    normal:normalize({x:Math.cos(angle),y:-ring.slope,z:Math.sin(angle)})};
}
